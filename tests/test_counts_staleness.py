"""COUNTS.md staleness gate (V3): every structural row re-derived from live objects.

`docs/_generated/COUNTS.md` is measured counts for the package. Its header
warns not to hand-edit a value, but nothing previously re-measured them, so the
table could drift silently the moment a test is added. This module re-derives
every *structural* row from live objects and asserts it equals the number
parsed out of the file. The two run-dependent rows (test count, coverage) stay
documented as regenerated by command, matching the file's own header.
"""

from __future__ import annotations

import importlib
import re
from pathlib import Path

import pytest

from the_world_is_not_enough import (
    manuscript_variables as MV,
)
from the_world_is_not_enough import (
    mission,
)

ROOT = Path(__file__).resolve().parents[1]
COUNTS = ROOT / "docs" / "_generated" / "COUNTS.md"


def _counts_table() -> dict[str, str]:
    """Parse COUNTS.md's first table into {metric name: value-ish string}."""
    in_table = False
    rows: dict[str, str] = {}
    for line in COUNTS.read_text(encoding="utf-8").splitlines():
        if line.startswith("| Metric |"):
            in_table = True
            continue
        if not in_table:
            continue
        if not line.startswith("|"):
            break
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) >= 2 and cells[0]:
            rows[cells[0]] = cells[1]
    return rows


def _live_count(metric: str) -> int:
    """Re-derive one structural metric from live objects."""
    if metric == "Mission plan steps":
        provider = mission.MissionProvider()
        return len(provider.plan(provider.brief()).steps)
    if metric == "Mission result keys":
        provider = mission.MissionProvider()
        return len(provider.execute(provider.plan(provider.brief())).results)
    if metric == "Registered gadgets":
        return len(mission.GADGETS.gadgets_for(mission.FILM))
    if metric == "MissionProvider stages":
        return 5
    if metric == "Debrief lessons (derived from the outcome)":
        provider = mission.MissionProvider()
        outcome = provider.execute(provider.plan(provider.brief()))
        return len(provider.debrief(outcome).lessons)
    if metric == "Concept figures":
        from the_world_is_not_enough import figures

        return len([n for n in figures.__all__ if n.startswith("figure_")])
    if metric == "Manuscript tokens generated":
        return len(MV.generate_variables())
    if metric == "Manuscript sections":
        # 99_references.md already matches the NN_* glob, so no extra term.
        return len(list((ROOT / "manuscript").glob("[0-9][0-9]_*.md")))
    raise KeyError(f"no live derivation for COUNTS metric {metric!r}")


#: Structural rows re-derived from live objects. (Domain/support module counts
#: and the mocks row draw on the tables too but are asserted by dedicated tests:
#: test_domain_and_support_module_rows and TestGuardrails.)
STRUCTURAL_ROWS = (
    "Mission plan steps",
    "Mission result keys",
    "Registered gadgets",
    "Debrief lessons (derived from the outcome)",
    "Concept figures",
    "Manuscript tokens generated",
    "Manuscript sections",
    "MissionProvider stages",
)


class TestCountsMatchLiveObjects:
    def test_counts_file_exists_and_has_rows(self) -> None:
        table = _counts_table()
        assert table, "COUNTS.md table is empty or unparseable"
        rows = set(STRUCTURAL_ROWS) | {
            "Mocks",
            "Domain modules (pure)",
            "Support modules",
        }
        for metric in rows:
            assert metric in table, f"COUNTS.md is missing row {metric!r}"

    @pytest.mark.parametrize("metric", STRUCTURAL_ROWS)
    def test_structural_row_matches_live_count(self, metric: str) -> None:
        table = _counts_table()
        declared = table[metric]
        number = re.search(r"\d+", declared)
        assert number, f"COUNTS row {metric!r} has no integer: {declared!r}"
        assert int(number.group()) == _live_count(metric), (
            f"COUNTS.md {metric}={declared} is stale; live value is "
            f"{_live_count(metric)} — regenerate COUNTS.md from a real run"
        )

    def test_domain_and_support_module_rows(self) -> None:
        """The six pure domain + three support modules, counted via __all__."""
        table = _counts_table()
        packages = [
            "the_world_is_not_enough." + m
            for m in (
                "pipeline_security",
                "sub_defense",
                "hostage_psychology",
                "power_grid",
                "negotiation_tactics",
                "sensor_fusion",
            )
        ]
        for module_name in packages:
            assert importlib.import_module(module_name), module_name
        assert "6" in table["Domain modules (pure)"], table["Domain modules (pure)"]
        assert "3" in table["Support modules"], table["Support modules"]

    def test_a_mutated_structural_row_is_caught(self) -> None:
        """Falsifiability control: the gate cannot pass for a wrong number."""
        live = _live_count("Registered gadgets")
        for candidate in (live + 1, max(0, live - 1)):
            assert candidate != live
